// Uses the real Studio server with a scripted model and isolated local storage.
const assert = require('node:assert/strict');
const { withFixture } = require('./browser_fixture.cjs');

async function verify(page, url) {
  const errors = [], submitted = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', r => {
    if (r.method()==='POST' && r.url()===url+'api/runs') submitted.push(r.postDataJSON());
  });
  const roleDialog=page.locator('#role-dialog');
  const dialogForm=page.locator('#dialog-form form');
  const navRoles=page.getByRole('link',{name:'角色库',exact:true});
  await page.goto(url);
  await navRoles.click();
  await page.getByRole('button',{name:'创建角色'}).click();
  await roleDialog.getByLabel('角色名称').fill('电脑维护');
  await roleDialog.getByLabel('角色职责').fill('维护本机项目。');
  await roleDialog.getByRole('button',{name:'保存角色'}).click();
  await page.getByRole('heading',{name:'电脑维护',exact:true}).waitFor();
  const roleID=await page.locator('.role-title code').innerText();
  assert.match(roleID,/^assistant-[a-f0-9]{8}$/);
  const detailURL=page.url();

  await page.getByRole('button',{name:'编辑角色'}).click();
  await roleDialog.getByLabel('角色名称').fill('项目维护');
  await roleDialog.getByRole('button',{name:'保存角色'}).click();
  await page.getByRole('heading',{name:'项目维护',exact:true}).waitFor();
  await page.getByRole('button',{name:'添加记忆'}).click();
  await roleDialog.getByLabel('标题').fill('偏好');
  await roleDialog.getByLabel('记忆内容').fill('始终保留 <本地备份>。');
  await roleDialog.getByRole('button',{name:'保存记忆'}).click();
  const memory=page.locator('.knowledge-card').filter({hasText:'偏好'});
  await memory.getByText('始终保留 <本地备份>。',{exact:true}).waitFor();
  await memory.getByRole('button',{name:'编辑偏好'}).click();
  await roleDialog.getByLabel('记忆内容').fill('保留两份 <本地备份>。');
  await roleDialog.getByRole('button',{name:'保存修改'}).click();
  await memory.getByText('保留两份 <本地备份>。',{exact:true}).waitFor();
  await memory.getByRole('button',{name:'归档'}).click();
  await memory.waitFor({state:'detached'});
  await page.getByRole('button',{name:'已处理'}).click();
  await memory.getByRole('button',{name:'恢复使用'}).click();
  await memory.waitFor({state:'detached'});
  await page.getByRole('button',{name:'当前',exact:true}).click();
  await memory.getByText('已启用',{exact:true}).waitFor();

  await page.getByRole('button',{name:'新建私聊',exact:true}).click();
  assert.equal(await dialogForm.locator('[name="recipient"]').inputValue(),roleID);
  await dialogForm.getByRole('button',{name:'选择文件夹'}).click();
  await page.waitForFunction(()=>document.querySelector('#dialog-form [name="workspace_path"]').value.length>0);
  await dialogForm.locator('[name="objective"]').fill('提出重启验证的技能和快速测试偏好，交给我确认。');
  await dialogForm.getByRole('button',{name:'发送'}).click();
  await page.getByText('已提交两项建议。',{exact:true}).waitFor();
  const firstURL=page.url();
  assert.equal(submitted[0].conversation.recipient,roleID);
  assert.deepEqual(submitted[0].conversation.members,[roleID]);
  assert.equal(submitted[0].conversation.profiles,undefined);
  const detail=await (await page.request.get(url+'api/runs/'+new URL(firstURL).hash.split('/')[1])).json();
  assert.equal(detail.conversation.profiles.find(p=>p.id===roleID).name,'项目维护');
  await page.goto(detailURL);
  await page.getByRole('link',{name:'继续最近私聊'}).waitFor();
  await page.getByRole('button',{name:/待确认/}).click();
  await page.locator('.knowledge-card').filter({hasText:'测试偏好'}).getByRole('button',{name:'拒绝'}).click();
  await page.getByRole('button',{name:'已处理'}).click();
  await page.locator('.knowledge-card').filter({hasText:'测试偏好'}).getByText('已拒绝',{exact:true}).waitFor();
  await page.getByRole('button',{name:'技能',exact:true}).click();
  await page.getByRole('button',{name:/待确认/}).click();
  const skill=page.locator('.knowledge-card').filter({hasText:'重启验证'});
  await skill.getByRole('button',{name:'确认启用'}).click();
  await skill.waitFor({state:'detached'});
  await page.getByRole('button',{name:'当前',exact:true}).click();
  await skill.getByText('已启用',{exact:true}).waitFor();
  await skill.getByRole('link',{name:'来源对话'}).waitFor();
  await page.getByRole('button',{name:'添加技能'}).click();
  await roleDialog.getByLabel('标题').fill('项目发布');
  await roleDialog.getByLabel('操作步骤').fill('核对发布清单。');
  await roleDialog.getByLabel('适用范围').selectOption('project');
  const projectID=await roleDialog.locator('[name="project"]').inputValue();
  assert.equal(projectID,submitted[0].workspace_path);
  await roleDialog.getByRole('button',{name:'保存技能'}).click();
  await page.locator('.knowledge-card').filter({hasText:'项目发布'}).getByText('核对发布清单。').waitFor();

  await page.getByRole('link',{name:'继续最近私聊'}).click();
  assert.equal(page.url(),firstURL);
  await page.goto(detailURL);
  await page.getByRole('button',{name:'新建私聊',exact:true}).click();
  await dialogForm.locator('[name="objective"]').fill('另一个独立项目。');
  await dialogForm.getByRole('button',{name:'发送'}).click();
  await page.getByText('已收到本轮消息。',{exact:true}).waitFor();
  assert.notEqual(page.url(),firstURL);
  assert.equal(submitted[1].conversation.recipient,roleID);
  assert.equal(submitted[1].conversation.parent_run_id,undefined);
  await page.goto(detailURL);
  await page.locator('.role-conversations a').nth(1).waitFor();
  await page.setViewportSize({width:380,height:750});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.getByRole('button',{name:'展开导航'}).click();
  await navRoles.click();
  await page.getByRole('link',{name:/项目维护/}).click();
  await page.getByRole('heading',{name:'项目维护',exact:true}).waitFor();
  await page.getByRole('link',{name:'返回角色库'}).click();
  await page.getByRole('link',{name:/旧版维护助手/}).click();
  const legacy=page.locator('.legacy-room').filter({hasText:'旧项目交接记录'});
  await legacy.getByRole('button',{name:'关联已有会话'}).waitFor();
  assert.equal(await page.locator('.legacy-room').filter({hasText:'另一位同名成员'}).count(),0);
  const oldLink=await legacy.getByRole('link').getAttribute('href');
  assert.equal(await page.locator('.role-conversations a').count(),0);
  await legacy.getByRole('button',{name:'关联已有会话'}).click();
  await legacy.waitFor({state:'detached'});
  await page.locator('.role-conversations').getByRole('link',{name:/旧项目交接记录/}).click();
  assert.equal(new URL(page.url()).hash,oldLink);
  await page.locator('.reply-form [name="message"]').fill('请记住：每次修改前创建备份。');
  await page.locator('.reply-form').getByRole('button',{name:'发送'}).click();
  await page.getByText('旧项目已继续。',{exact:true}).waitFor();
  await page.goto(url+'#roles/legacy');
  await page.locator('.knowledge-card').getByText('每次修改前创建备份。',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('Role creation/editing, independent and resumed DMs, candidate review, project scopes, revisions, archiving, explicit legacy binding, direct memory capture and mobile navigation passed.');
}

withFixture('serve_role_fixture',verify).catch(error=>{console.error(error);process.exitCode=1;});
